CREATE TABLE usuarios
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                     VARCHAR(120) NOT NULL,
    email                    VARCHAR(120) NOT NULL UNIQUE,
    senha_hash               VARCHAR(255) NOT NULL,
    role                     VARCHAR(30)  NOT NULL,
    consentimento_fidelidade BOOLEAN   DEFAULT FALSE,
    criado_em                TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE unidades
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     VARCHAR(120) NOT NULL,
    cidade   VARCHAR(80)  NOT NULL,
    endereco VARCHAR(200),
    ativa    BOOLEAN DEFAULT TRUE
);

CREATE TABLE produtos
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120)   NOT NULL,
    descricao VARCHAR(255),
    preco     DECIMAL(10, 2) NOT NULL,
    ativo     BOOLEAN DEFAULT TRUE
);

CREATE TABLE estoques
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INT    NOT NULL DEFAULT 0,
    CONSTRAINT fk_estoque_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id),
    CONSTRAINT fk_estoque_produto FOREIGN KEY (produto_id) REFERENCES produtos (id),
    CONSTRAINT uk_estoque_unidade_produto UNIQUE (unidade_id, produto_id)
);

CREATE TABLE pedidos
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id   BIGINT         NOT NULL,
    unidade_id   BIGINT         NOT NULL,
    canal_pedido VARCHAR(20)    NOT NULL,
    status       VARCHAR(30)    NOT NULL,
    valor_total  DECIMAL(10, 2) NOT NULL,
    criado_em    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id) REFERENCES usuarios (id),
    CONSTRAINT fk_pedido_unidade FOREIGN KEY (unidade_id) REFERENCES unidades (id)
);

CREATE TABLE itens_pedido
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      BIGINT         NOT NULL,
    produto_id     BIGINT         NOT NULL,
    quantidade     INT            NOT NULL,
    preco_unitario DECIMAL(10, 2) NOT NULL,
    CONSTRAINT fk_item_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT fk_item_produto FOREIGN KEY (produto_id) REFERENCES produtos (id)
);

CREATE TABLE pagamentos
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id    BIGINT         NOT NULL,
    status       VARCHAR(30)    NOT NULL,
    valor        DECIMAL(10, 2) NOT NULL,
    transacao_id VARCHAR(100),
    criado_em    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pagamento_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id)
);

CREATE TABLE auditorias
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao        VARCHAR(100) NOT NULL,
    entidade    VARCHAR(80),
    entidade_id BIGINT,
    detalhes    VARCHAR(500),
    criado_em   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);